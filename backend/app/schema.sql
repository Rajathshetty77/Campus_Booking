-- Database schema (Postgres / Supabase). Applied automatically on backend start-up; safe to re-run.
-- You can also paste it into the Supabase SQL editor.

CREATE TABLE IF NOT EXISTS users (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       text NOT NULL UNIQUE CHECK (email = lower(email)),
  name        text NOT NULL,
  role        text NOT NULL DEFAULT 'member' CHECK (role IN ('member', 'admin')),
  password_hash text,
  department  text,
  created_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS password_hash text;

CREATE TABLE IF NOT EXISTS sessions (
  token       text PRIMARY KEY,
  user_id     integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at  double precision NOT NULL
);

CREATE TABLE IF NOT EXISTS venues (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name              text NOT NULL,
  block             text NOT NULL DEFAULT '',
  type              text NOT NULL,
  capacity          integer NOT NULL,
  features          jsonb NOT NULL DEFAULT '[]',
  color             text NOT NULL,
  requires_approval boolean NOT NULL DEFAULT true,
  open_time         text NOT NULL DEFAULT '07:00',
  close_time        text NOT NULL DEFAULT '21:00',
  active            boolean NOT NULL DEFAULT true
);

-- start_ts / end_ts are IST wall-clock strings "YYYY-MM-DD HH:MM". COLLATE "C" keeps comparisons
-- byte-wise, so overlap checks are plain string comparisons whatever the database locale.
CREATE TABLE IF NOT EXISTS bookings (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       text NOT NULL,
  description text NOT NULL DEFAULT '',
  event_type  text NOT NULL,
  organizer   text NOT NULL DEFAULT '',
  venue_id    integer NOT NULL REFERENCES venues(id),
  user_id     integer NOT NULL REFERENCES users(id),
  start_ts    text COLLATE "C" NOT NULL,
  end_ts      text COLLATE "C" NOT NULL,
  attendees   integer NOT NULL DEFAULT 0,
  status      text NOT NULL DEFAULT 'pending'
              CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
  admin_note  text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_bookings_venue_time ON bookings (venue_id, start_ts, end_ts);
CREATE INDEX IF NOT EXISTS idx_bookings_user ON bookings (user_id);

-- Only the backend (connecting as the database owner) touches these tables. Row Level Security with
-- no policies blocks Supabase's auto-generated REST API (anon / authenticated keys) from reading them.
ALTER TABLE users    ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE venues   ENABLE ROW LEVEL SECURITY;
ALTER TABLE bookings ENABLE ROW LEVEL SECURITY;
